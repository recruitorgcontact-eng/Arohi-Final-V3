// Helper to generate personalized lines with user's name
export function buildPersonalizedMotivationalLines(firstName: string) {
  const cleanName = firstName?.trim();
  
  return BASE_MOTIVATIONAL_HEADLINES.map(item => {
    if (!cleanName) {
      return {
        before: item.before,
        name: "",
        after: item.after,
        gradientDark: item.gradientDark,
        gradientLight: item.gradientLight,
        tag: item.tag
      };
    }
    
    // Add comma and name gracefully
    return {
      before: `${item.before}, `,
      name: cleanName,
      after: item.after,
      gradientDark: item.gradientDark,
      gradientLight: item.gradientLight,
      tag: item.tag
    };
  });
}

// Fisher-Yates array shuffler
export function shuffleHeadlines<T>(array: T[]): T[] {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}
